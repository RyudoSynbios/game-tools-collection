export function chocoboCourseFragment(
  name: string,
  offset: number,
  bit: number,
): ItemSection {
  return {
    name,
    type: "section",
    flex: true,
    items: [
      {
        name: "Status",
        offset: 0x2bb,
        type: "variable",
        dataType: "bit",
        bit,
        resource: "booleanCleared",
      },
      {
        name: "Time",
        type: "group",
        mode: "chrono",
        items: [
          {
            offset,
            type: "variable",
            dataType: "uint8",
            max: 1,
          },
          {
            offset: offset + 0x1,
            type: "variable",
            dataType: "uint8",
            leadingZeros: 1,
            max: 59,
          },
          {
            offset: offset + 0x2,
            type: "variable",
            dataType: "uint8",
            max: 9,
          },
        ],
      },
    ],
  };
}
